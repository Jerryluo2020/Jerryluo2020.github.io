import assert from 'node:assert/strict';
import { installSnapshot } from '../github-pages/snapshot.ts';
import { shiftDate } from '../lib/pattern.ts';
const bars=Array.from({length:140},(_,i)=>({date:shiftDate('2025-01-01',i),open:10+i/10,close:10+i/10,high:11+i/10,low:9+i/10,volume:1000+i,amount:null,turnover:null}));
const stocks=[{code:'001210',name:'样本',market:0},{code:'000002',name:'同形',market:0},{code:'000003',name:'缺数据',market:0},{code:'000004',name:'ST排除',market:0},{code:'000005',name:'停牌',market:0}];
const rows={'0.001210':bars,'0.000002':bars.map(b=>({...b,open:b.open*2,close:b.close*2,high:b.high*2,low:b.low*2})), '0.000005':bars.slice(0,-1)};
globalThis.fetch=()=>{throw Error('Unexpected external network request');};
const handler=installSnapshot({version:1,date:bars.at(-1).date,provider:'tencent',stocks,total:5,index:bars,minSampleDate:bars[60].date,rankings:{test:true}},async key=>{if(!rows[key])throw Error('missing');return rows[key];});
const q=new URLSearchParams({code:'001210',start:bars[100].date,end:bars[109].date,date:bars.at(-1).date});
const preview=await handler('/api/patterns?'+q);
assert.equal(preview.reference.points.length,10);
assert.equal(preview.reference.stock.name,'样本');
const result=await handler('/api/patterns?'+q,{stocks});
assert.equal(result.matches.length,1);assert.equal(result.failed,1);assert.equal(result.skipped,3);
assert.equal(result.matches[0].parts[5],null);
const exact=new URLSearchParams({code:'001210',start:bars[130].date,end:bars[139].date,date:bars.at(-1).date});
const identity=await handler('/api/patterns?'+exact,{stocks:[stocks[1]]});
assert.ok(Math.abs(identity.matches[0].score-100)<1e-8);
await assert.rejects(handler('/api/patterns?'+q.toString().replace(bars.at(-1).date,'2025-12-31')),/快照最新交易日/);
const early=new URLSearchParams({code:'001210',start:bars[20].date,end:bars[100].date,date:bars.at(-1).date});
await assert.rejects(handler('/api/patterns?'+early),/最早|开始日期/);
assert.deepEqual(await handler('/api/stocks'),{test:true});
console.log('PASS: offline preview, identity/scale invariance, missing factor, failure counts, self/ST/suspension exclusion, snapshot date bounds, rankings');
